joblib.dump(scaler, os.path.join(MODEL_DIR, "scaler.joblib"))
joblib.dump(feature_names, os.path.join(MODEL_DIR, "feature_names.joblib"))
joblib.dump(
    {"dt": tuned_dt, "rf": tuned_rf, "xgb": tuned_xgb},
    os.path.join(MODEL_DIR, "hard_voting_ensemble_members.joblib")
)
print(f"\nSaved scaler, feature schema, and ensemble members to {MODEL_DIR}")

