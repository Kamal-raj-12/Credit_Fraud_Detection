# ============================================================
# Fraud Detection - GridSearch-Optimized Models + Hard Voting Ensemble
#
# Three classifiers (Decision Tree, Random Forest, XGBoost) tuned via
# GridSearchCV, then combined into a Hard Voting ensemble. The core
# imbalance-handling choices (class_weight='balanced' for RF,
# scale_pos_weight for XGBoost) are kept fixed since those are
# deliberate design decisions, not something to search over; the grid
# tunes capacity/regularization parameters (depth, leaf size, learning
# rate, subsampling, etc.) around them.
#
# All models and grid-search results are cached to Google Drive —
# rerunning this script will not retrain anything already saved.
