def engineer_features(data: pd.DataFrame) -> pd.DataFrame:
    data = data.copy()
    data["amount_to_orig_balance"] = data["amount"] / (data["oldbalanceOrg"] + 1.0)
    data["amount_to_dest_balance"] = data["amount"] / (data["oldbalanceDest"] + 1.0)

