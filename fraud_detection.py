def load_or_fit(path, fit_fn, expected_n_features=None):
    if os.path.exists(path):
        cached = joblib.load(path)
        if expected_n_features is not None and hasattr(cached, "n_features_in_"):
            if cached.n_features_in_ != expected_n_features:
                print(f"  [STALE CACHE] {os.path.basename(path)} was trained on "
                      f"{cached.n_features_in_} features, current run has "
                      f"{expected_n_features}. Discarding and refitting...")
                os.remove(path)
            else:
                print(f"  [CACHE HIT] Loaded {os.path.basename(path)}")
                return cached
        else:
            print(f"  [CACHE HIT] Loaded {os.path.basename(path)}")
            return cached

    print(f"  [CACHE MISS] Fitting and saving {os.path.basename(path)}...")
    result = fit_fn()
    joblib.dump(result, path)
    return result

